#!/usr/bin/env node

const fs = require('fs')
const path = require('path')
const contentEntries = require('./content-asset-entries')

const root = path.resolve(__dirname, '..')
const output = path.join(root, 'src/stores/lib/content-assets-manifest.js')
const imagePattern = /\.(?:png|jpe?g|webp|gif|svg)$/i

function main() {
  const manifest = {}

  for (const { kind, slug } of contentEntries) {
    const sourceDir = path.join(root, 'src/assets', kind, slug)

    if (!fs.existsSync(sourceDir)) {
      throw new Error(`Missing asset directory: ${path.relative(root, sourceDir)}`)
    }

    const files = fs.readdirSync(sourceDir)
      .filter(file => imagePattern.test(file))
      .filter(file => fs.statSync(path.join(sourceDir, file)).isFile())
      .sort(naturalCompare)

    manifest[kind] ||= {}
    manifest[kind][slug] = files.map(file => {
      const base = file.replace(/\.[^.]+$/, '').toLowerCase()

      return {
        file,
        base,
        original: originalUrl(kind, slug, file),
      }
    })
  }

  const source = `// This file is generated by scripts/write-content-assets-manifest.js.\n` +
    `const contentAssetManifest = ${JSON.stringify(manifest, null, 2)}\n\n` +
    `export function assetEntriesFor(kind, slug) {\n` +
    `  return contentAssetManifest[kind]?.[slug] || []\n` +
    `}\n`

  fs.writeFileSync(output, source)
  console.log(`Wrote ${path.relative(root, output)}.`)
}

function originalUrl(kind, slug, file) {
  return ['originals', kind, slug, file]
    .map(segment => encodeURIComponent(segment))
    .join('/')
    .replace(/^/, '/')
}

function naturalCompare(a, b) {
  return a.localeCompare(b, undefined, { numeric: true, sensitivity: 'base' })
}

main()
