#!/usr/bin/env node

const fs = require('fs')
const path = require('path')

const root = path.resolve(__dirname, '..')
const responsiveRoot = path.join(root, 'public/img/responsive')
const output = path.join(root, 'src/stores/lib/responsive-manifest.js')

function main() {
  const manifest = {}

  if (fs.existsSync(responsiveRoot)) {
    for (const kind of sortedDirectories(responsiveRoot)) {
      manifest[kind] = {}
      const kindDir = path.join(responsiveRoot, kind)

      for (const slug of sortedDirectories(kindDir)) {
        const slugDir = path.join(kindDir, slug)
        const files = fs.readdirSync(slugDir)
          .filter(file => /\.webp$/i.test(file))
          .sort(naturalCompare)

        for (const file of files) {
          const match = file.match(/^(.+)-(\d+)w\.webp$/i)
          if (!match) continue

          const base = match[1].toLowerCase()
          const width = Number(match[2])

          manifest[kind][slug] ||= {}
          manifest[kind][slug][base] ||= []
          manifest[kind][slug][base].push({
            width,
            src: `/img/responsive/${kind}/${slug}/${file}`,
          })
        }
      }
    }
  }

  for (const kind of Object.keys(manifest)) {
    for (const slug of Object.keys(manifest[kind])) {
      for (const base of Object.keys(manifest[kind][slug])) {
        manifest[kind][slug][base].sort((a, b) => a.width - b.width)
      }
    }
  }

  const source = `// This file is generated by scripts/write-responsive-manifest.js.\n` +
    `const responsiveManifest = ${JSON.stringify(manifest, null, 2)}\n\n` +
    `export function responsiveFor(kind, slug, base) {\n` +
    `  return responsiveManifest[kind]?.[slug]?.[base] || []\n` +
    `}\n`

  fs.writeFileSync(output, source)
  console.log(`Wrote ${path.relative(root, output)}.`)
}

function sortedDirectories(dir) {
  return fs.readdirSync(dir)
    .filter(name => fs.statSync(path.join(dir, name)).isDirectory())
    .sort(naturalCompare)
}

function naturalCompare(a, b) {
  return a.localeCompare(b, undefined, { numeric: true, sensitivity: 'base' })
}

main()
